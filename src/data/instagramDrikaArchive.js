/**
 * Retorna os posts e Reels nativos relacionados a um serviceId do catálogo (ex: 'corte', 'drycut', 'chanel-longbob')
 */
export function getPostsByServiceId(serviceId, limit = 6) {
  if (!serviceId) return DRIKA_INSTAGRAM_POSTS.slice(0, limit);
  const matched = DRIKA_INSTAGRAM_POSTS.filter(
    (p) => Array.isArray(p.serviceIds) && p.serviceIds.includes(serviceId)
  );
  return matched.slice(0, limit);
}

